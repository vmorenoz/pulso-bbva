import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
import {install,uninstall} from '../lib/install.mjs';
import {temp} from './helpers.mjs';

test('installed plugin prepares identity, migrates legacy and observes hooks using distributed core',async t=>{
  const dependencies=process.env.PULSO_TEST_PLUGIN_NODE_MODULES||path.join(os.homedir(),'.config/opencode/node_modules');
  if(!fs.existsSync(path.join(dependencies,'@opencode-ai/plugin')))return t.skip('Local OpenCode v1 dependencies unavailable');
  const homeDir=temp(t),directory=temp(t),options={homeDir,env:{}};
  install(options);
  fs.symlinkSync(dependencies,path.join(homeDir,'.config/opencode/node_modules'));
  const {PulsoPlugin}=await import(pathToFileURL(path.join(homeDir,'.config/opencode/plugins/pulso/index.mjs')).href);
  const plugin=await PulsoPlugin({directory,homeDir}),context={directory};
  assert.equal(fs.existsSync(path.join(directory,'.pulso')),false);
  const before=await plugin.tool.pulso_workspace.execute({action:'status'},context);
  assert.equal(before.metadata.ok,true);assert.equal(fs.existsSync(path.join(directory,'.pulso')),false);
  fs.mkdirSync(path.join(directory,'.pulso/tasks'),{recursive:true});
  fs.writeFileSync(path.join(directory,'.pulso/state.json'),JSON.stringify({schema_version:1}));
  fs.writeFileSync(path.join(directory,'.pulso/tasks/PULSO-001.json'),JSON.stringify({id:'PULSO-001',title:'Legacy',objective:'Preserve scope',status:'implemented',acceptance_criteria:['Review legacy result']}));
  assert.match((await plugin.tool.pulso_workspace.execute({action:'status'},context)).output,/legacy detectado/);
  const prepared=await plugin.tool.pulso_workspace.execute({action:'prepare'},context);
  assert.equal(prepared.metadata.ok,true,prepared.output);assert.match(prepared.output,/migrados 1/);
  const identity=JSON.parse(fs.readFileSync(path.join(directory,'.pulso/project.json'),'utf8'));
  const registry=path.join(homeDir,'.pulso/projects',`${identity.projectId}.json`);
  assert.deepEqual(JSON.parse(fs.readFileSync(registry,'utf8')).locations,[directory]);
  assert.equal((await plugin.tool.pulso_workspace.execute({action:'prepare'},context)).metadata.ok,true);
  const created=await plugin.tool.pulso_work.execute({action:'create',title:'New work',objective:'Check installed identity module',criterion:'Automatic UUID',verification:'Read actual canonical work'},context);
  assert.equal(created.metadata.ok,true,created.output);assert.match(created.output,/PULSO-[0-9a-f]{8}-/);
  const input={tool:'task',sessionID:'ses_installed',callID:'call_installed'},args={prompt:'workId: PULSO-001\ntaskId: T-1\nsecret not stored'};
  await plugin['tool.execute.before'](input,{args});
  await plugin['tool.execute.after']({...input,args},{metadata:{sessionId:'ses_child'},output:'secret output'});
  await plugin['tool.execute.before'](input,{args});
  const attempts=await plugin.tool.pulso_workspace.execute({action:'attempts'},context);
  assert.equal(attempts.metadata.ok,true);assert.match(attempts.output,/PULSO-001.*T-1.*completed.*vida desconocida/);
  const state=fs.readFileSync(path.join(directory,'.pulso/state.json')),registered=fs.readFileSync(registry);
  uninstall(options);
  assert.deepEqual(fs.readFileSync(path.join(directory,'.pulso/state.json')),state);
  assert.deepEqual(fs.readFileSync(registry),registered);
  assert.ok(fs.existsSync(path.join(homeDir,'.config/opencode/node_modules/@opencode-ai/plugin/package.json')));
});
